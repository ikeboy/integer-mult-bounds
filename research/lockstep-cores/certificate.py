#!/usr/bin/env python3
"""Exact certificate: PR128/PR129 shared completed cores executed in lockstep.

Inputs (regenerated by the two scripts in this directory):
  lockstep-bit-profile.json  bit side (h = 23): PR128's minimal-V word, PR129's 161 classes of 11, lockstep;
  complex-row.json           complex side (h = 24): PR117's DAG with lifted and shrunk frames, per-core row histogram.
Complex lockstep profile: PR128's 87 groups (83 of 24, 4 of 8). The per-core row children of the cores of a group
merge into one child of width |J| r; data fronts, data macros and endpoint copies stay per core; each role of a
partial group keeps PR128's complement of width 384; W = 2N + 2*87*R.
Computes the largest coarse bit and complex savings on the 10^-10 grid (PR104's exact moment), the stopped bit
saving (stopping at theta = 1/1000 with PR104's retained leaf saving), the finite bridge (scalar term = DAG additions
plus every readout multiply-add) and the 47-constraint assembly at the largest kappa on the 10^-10 grid.
Usage: python3 research/lockstep-cores/certificate.py      (writes certificate.json)
Prepared by Avi Eisenberg (ikeboy) with Anthropic Claude assistance. Apache-2.0.
"""
import json
import sys
from collections import Counter
from fractions import Fraction as Q
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from partial_swap_network import moment                                    # noqa: E402
from copied_centers_network import finite_bridge as copied_bridge          # noqa: E402
from structured_bulk_assembly import assembly, js                          # noqa: E402

GRID = 10**10
ATOM = Q(1, 1000)                       # PR104 stopping exponent theta
OLD = Q(384599, 10**10)                 # PR104 retained ordinary leaf saving
PHASE_STOP = Q(1, 10**6)                # PR104 beta
COMPLEX_GROUPS = ((83, 24), (4, 8))     # PR128's signed partition of the 2024 triples


def require(ok, msg):
    if not ok:
        raise SystemExit('FAIL: ' + msg)


def contracts(m, W, z, a):
    try:
        moment(m, W, z, a, True)
        return True
    except SystemExit:
        return False
    except Exception:
        return False


def largest(m, W, z, lo, hi):
    a, b = int(lo * GRID), int(hi * GRID)
    require(contracts(m, W, z, Q(a, GRID)) and not contracts(m, W, z, Q(b, GRID)), 'bracket')
    while b - a > 1:
        mid = (a + b) // 2
        a, b = (mid, b) if contracts(m, W, z, Q(mid, GRID)) else (a, mid)
    return Q(a, GRID)


def complex_profile(row):
    h, v, R = row['h'], row['v'], row['R']; m = h * h; N = v * v; L = 2 * v * h * (h - 1)
    H = {int(t): c for t, c in row['row_histogram'].items()}
    require(sum(t * c for t, c in H.items()) == h * R + h * (h - 1), 'row rank')
    require(sum(n * s for n, s in COMPLEX_GROUPS) == v, 'groups cover the 2024 triples')
    z = Counter()
    for count, size in COMPLEX_GROUPS:
        for t, c in H.items(): z[size * t] += 2 * count * c          # merged row children of a group
    z[1] += N; z[h - 1] += 4 * N; z[(h - 1) ** 2] += 2 * N            # endpoint copies, data fronts, data macros
    z[m - 8 * h] += 2 * 4 * R                                         # complement of each role of a partial group
    W = 2 * N + 2 * sum(n for n, s in COMPLEX_GROUPS) * R
    require(sum(t * c for t, c in z.items()) == W * m - N + L, 'complex rank mass')
    require(all(0 < t < m for t in z), 'complex children below m')
    return dict(h=h, v=v, m=m, N=N, R=R, W=W, L=L, total_rank=W * m - N + L, deficit=N - L, maxchild=max(z),
                additions=row['additions'], readout_terms=row['readout_terms'],
                child_multiplicities=dict(sorted(z.items())))


def main():
    bit = json.loads((HERE / 'lockstep-bit-profile.json').read_text())
    bit['child_multiplicities'] = {int(t): c for t, c in bit['child_multiplicities'].items()}
    row = json.loads((HERE / 'complex-row.json').read_text())
    phase = complex_profile(row)
    zb, zc = bit['child_multiplicities'], phase['child_multiplicities']
    require(sum(t * c for t, c in zb.items()) == bit['total_rank'] == bit['W'] * bit['m'] - bit['N'] + bit['L'], 'bit rank')
    coarse = largest(bit['m'], bit['W'], zb, Q(7, 10**5), Q(1, 10**3))
    ac = largest(phase['m'], phase['W'], zc, Q(7, 10**5), Q(1, 10**3))
    bm = moment(bit['m'], bit['W'], zb, coarse, True)
    cm = moment(phase['m'], phase['W'], zc, ac, True)
    require(not contracts(bit['m'], bit['W'], zb, coarse + Q(1, GRID)), 'next coarse grid point rejected')
    require(not contracts(phase['m'], phase['W'], zc, ac + Q(1, GRID)), 'next complex grid point rejected')
    require(0 < OLD <= coarse < ATOM < 1, 'stopped-adapter exponents')
    ab = (1 - ATOM) * coarse + ATOM * OLD
    require(ATOM > ab, 'adapter toll subordinate to the stopped saving')
    abit = min(ab, (1 - PHASE_STOP) * ac - Q(1, GRID))

    rowb = dict(h=phase['h'], v=phase['v'], c=phase['additions'] + phase['readout_terms'], central_disjoint=24)
    previous = json.loads((ROOT / 'certificates' / 'copied-centers-network.json').read_text())
    bridge = copied_bridge(dict(m=bit['m'], W=bit['W'], maxchild=bit['maxchild']), phase, [rowb, rowb])
    old_bit = previous['finite_bridge']['bit']
    old_degree = old_bit['halving_degree'] * old_bit['wire_bits']
    require(old_degree == 252, 'inherited ordinary leaf row stock')
    coarse_bridge = bridge.pop('bit'); cpx = bridge['complex']
    coefficient = (coarse_bridge['halving_degree'] * coarse_bridge['wire_bits'] + old_degree +
                   cpx['halving_degree'] * cpx['wire_bits'])
    degree = 1000 * ((51 * coefficient) // 25000 + 1)
    require(Q(degree) > Q(51 * coefficient, 25), 'product stock strictly sufficient')
    bridge.update(bit_coarse=coarse_bridge, ordinary_leaf_row_degree=old_degree)
    bridge['rows'] = dict(coefficient=coefficient, degree=degree, suffix_slope=4 * degree,
                          degree_gap=Q(degree) - Q(51 * coefficient, 25),
                          contract='W_complex^D_complex * W_coarse^D_coarse * W_old^D_old; one preceding prefix and one padding; sequential reuse')
    bridge['semantic'].update(fixed_odd_divisor=21,
                              exact_grid='One common dyadic grid times the fixed odd divisor to K=G*(D_complex+1); no child rounding')

    def accepted(k):
        try:
            assembly(abit, ac, bridge, Q(k, GRID), beta=PHASE_STOP)
            return True
        except AssertionError:
            return False
    lo, hi = int(Q(7, 10**5) * GRID), int(ab * GRID) + 1
    require(accepted(lo) and not accepted(hi), 'kappa bracket')
    while hi - lo > 1:
        mid = (lo + hi) // 2
        lo, hi = (mid, hi) if accepted(mid) else (lo, mid)
    kappa = Q(lo, GRID)
    assembled = assembly(abit, ac, bridge, kappa, beta=PHASE_STOP)
    require(not accepted(lo + 1), 'next kappa grid point rejected')
    require(len(assembled['strict_constraints']) == 47 and len(assembled['margins']) == 7, 'complete assembly')
    assembled['parameters']['actual_bit_saving'] = ab
    result = dict(status='Conditional witness: PR128/PR129 shared completed cores executed in lockstep',
                  kappa=kappa,
                  bit=dict(coarse_saving=coarse, stopped_saving=ab, moment_gap=bm['strict_gap'],
                           counts={k: bit[k] for k in ('h', 'v', 'R', 'm', 'W', 'total_rank', 'maxchild', 'groups', 'group_size')}),
                  complex=dict(saving=ac, moment_gap=cm['strict_gap'],
                               counts={k: phase[k] for k in ('h', 'v', 'R', 'm', 'W', 'total_rank', 'maxchild', 'additions', 'readout_terms')},
                               groups=[list(g) for g in COMPLEX_GROUPS]),
                  finite_bridge=bridge, assembly=assembled,
                  base='PR129 head 2d0f27bc8f7c908dc3fac71355eef4f8f1565891')
    (HERE / 'certificate.json').write_text(json.dumps(js(result), indent=2, sort_keys=True) + '\n')
    print('PASS kappa = %s = %.10e' % (kappa, float(kappa)))
    print('coarse bit saving %s, stopped %s, complex saving %s' % (coarse, ab, ac))


if __name__ == '__main__':
    main()
